//! Unified async database endpoint: MySQL wire (mysql_async pooled) or
//! Postgres (tokio-postgres with a small internal async pool).
//!
//! Statements are generated by [`crate::dialect`] with the right
//! placeholder style; this layer only binds values and decodes rows.

use std::sync::Arc;

use mysql_async::prelude::Queryable;
use tokio::sync::{Mutex, Semaphore};

use crate::dialect::JdbcDialectKind;
use crate::url::JdbcUrl;
use crate::value::{SqlValue, mysql_value_to_sql};

/// Query result: column names + rows of driver-neutral values.
#[derive(Debug, Clone)]
pub struct QueryResult {
    pub columns: Vec<String>,
    pub rows: Vec<Vec<SqlValue>>,
}

impl QueryResult {
    pub fn scalar_i64(&self) -> Option<i64> {
        let row = self.rows.first()?;
        match row.first()? {
            SqlValue::Int(v) => Some(*v),
            SqlValue::UInt(v) => Some(*v as i64),
            SqlValue::Str(s) => s.parse().ok(),
            SqlValue::Float(f) => Some(*f as i64),
            _ => None,
        }
    }

    pub fn scalar_string(&self) -> Option<String> {
        let row = self.rows.first()?;
        match row.first()? {
            SqlValue::Str(s) => Some(s.clone()),
            SqlValue::Bytes(b) => Some(String::from_utf8_lossy(b).to_string()),
            other => other.as_text(),
        }
    }
}

// ---------------------------------------------------------------------------
// Postgres pool
// ---------------------------------------------------------------------------

struct PgPoolInner {
    config: tokio_postgres::Config,
    idle_tx: tokio::sync::mpsc::UnboundedSender<tokio_postgres::Client>,
    idle_rx: Mutex<tokio::sync::mpsc::UnboundedReceiver<tokio_postgres::Client>>,
    permits: Semaphore,
}

/// A small async Postgres connection pool (mirrors mysql_async's `Pool`
/// behavior: bounded concurrency, idle connections returned on drop).
#[derive(Clone)]
pub struct PgPool {
    inner: Arc<PgPoolInner>,
}

struct PgClientGuard {
    client: Option<tokio_postgres::Client>,
    pool: Arc<PgPoolInner>,
}

impl std::ops::Deref for PgClientGuard {
    type Target = tokio_postgres::Client;
    fn deref(&self) -> &Self::Target {
        self.client.as_ref().expect("client present until drop")
    }
}

impl Drop for PgClientGuard {
    fn drop(&mut self) {
        if let Some(client) = self.client.take() {
            if !client.is_closed() {
                let _ = self.pool.idle_tx.send(client);
            }
        }
    }
}

impl PgPool {
    pub fn new(config: tokio_postgres::Config, max_size: usize) -> Self {
        let (tx, rx) = tokio::sync::mpsc::unbounded_channel();
        PgPool {
            inner: Arc::new(PgPoolInner {
                config,
                idle_tx: tx,
                idle_rx: Mutex::new(rx),
                permits: Semaphore::new(max_size.max(1)),
            }),
        }
    }

    async fn get(&self) -> anyhow::Result<PgClientGuard> {
        let _permit = self.inner.permits.acquire().await?;
        if let Some(client) = self.inner.idle_rx.lock().await.recv().await {
            if !client.is_closed() {
                return Ok(PgClientGuard {
                    client: Some(client),
                    pool: self.inner.clone(),
                });
            }
        }
        let (client, connection) = self
            .inner
            .config
            .connect(tokio_postgres::NoTls)
            .await
            .map_err(|e| anyhow::anyhow!("postgres connect: {}", e))?;
        // Drive the connection; when it ends the client is marked closed.
        tokio::spawn(async move {
            if let Err(e) = connection.await {
                tracing::debug!("postgres connection ended: {}", e);
            }
        });
        Ok(PgClientGuard {
            client: Some(client),
            pool: self.inner.clone(),
        })
    }
}

/// Postgres parameter binding: text for most values (placeholders cast
/// explicitly), native bool / bytes. The binary wire formats are written
/// directly so the value kind never has to match the parameter type
/// declared by the statement.
#[derive(Debug)]
enum PgParam {
    Null,
    Bool(bool),
    Bytes(Vec<u8>),
    Text(String),
}

impl tokio_postgres::types::ToSql for PgParam {
    fn to_sql(
        &self,
        _ty: &tokio_postgres::types::Type,
        out: &mut tokio_postgres::types::private::BytesMut,
    ) -> Result<tokio_postgres::types::IsNull, Box<dyn std::error::Error + Sync + Send>> {
        use tokio_postgres::types::IsNull;
        match self {
            PgParam::Null => Ok(IsNull::Yes),
            PgParam::Bool(b) => {
                out.extend_from_slice(&[u8::from(*b)]);
                Ok(IsNull::No)
            }
            PgParam::Bytes(b) => {
                out.extend_from_slice(&(b.len() as i32).to_be_bytes());
                out.extend_from_slice(b);
                Ok(IsNull::No)
            }
            PgParam::Text(s) => {
                out.extend_from_slice(&(s.len() as i32).to_be_bytes());
                out.extend_from_slice(s.as_bytes());
                Ok(IsNull::No)
            }
        }
    }

    fn accepts(_ty: &tokio_postgres::types::Type) -> bool {
        true
    }

    tokio_postgres::types::to_sql_checked!();
}

fn pg_params(params: &[SqlValue]) -> Vec<PgParam> {
    params
        .iter()
        .map(|p| match p {
            SqlValue::Null => PgParam::Null,
            SqlValue::Bool(b) => PgParam::Bool(*b),
            SqlValue::Bytes(b) => PgParam::Bytes(b.clone()),
            other => match other.as_text() {
                Some(text) => PgParam::Text(text),
                None => PgParam::Null,
            },
        })
        .collect()
}

