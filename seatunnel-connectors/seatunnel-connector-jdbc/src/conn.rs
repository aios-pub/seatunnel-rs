/// A pooled async connection endpoint for one database.
#[derive(Clone)]
pub enum DbEndpoint {
    MySql(mysql_async::Pool),
    Postgres(PgPool),
}

impl DbEndpoint {
    /// Connect using the given URL and credentials, verifying the
    /// connection with a trivial query.
    pub async fn connect(
        url: &JdbcUrl,
        username: &str,
        password: &str,
        pool_size: usize,
    ) -> anyhow::Result<Self> {
        match url.dialect {
            JdbcDialectKind::Postgres => {
                let mut config = tokio_postgres::Config::new();
                config
                    .host(&url.host)
                    .port(url.port)
                    .user(username)
                    .password(password);
                if !url.database.is_empty() {
                    config.dbname(&url.database);
                }
                let pool = PgPool::new(config, pool_size);
                let guard = pool.get().await?;
                guard.simple_query("SELECT 1").await?;
                drop(guard);
                Ok(DbEndpoint::Postgres(pool))
            }
            JdbcDialectKind::MySql | JdbcDialectKind::TiDB => {
                let opts = mysql_async::OptsBuilder::default()
                    .ip_or_hostname(&url.host)
                    .tcp_port(url.port)
                    .user(Some(username))
                    .pass(Some(password))
                    .db_name(if url.database.is_empty() {
                        None
                    } else {
                        Some(url.database.as_str())
                    })
                    .pool_opts(
                        mysql_async::PoolOpts::new().with_constraints(
                            mysql_async::PoolConstraints::new(1, pool_size.max(1))
                                .ok_or_else(|| anyhow::anyhow!("invalid pool constraints"))?,
                        ),
                    );
                let pool = mysql_async::Pool::new(opts);
                let mut conn = pool.get_conn().await?;
                let _: Option<i32> = conn.query_first("SELECT 1").await?;
                drop(conn);
                Ok(DbEndpoint::MySql(pool))
            }
        }
    }

    /// Execute a statement that returns no rows; returns affected rows.
    pub async fn exec(&self, sql: &str, params: &[SqlValue]) -> anyhow::Result<u64> {
        match self {
            DbEndpoint::MySql(pool) => {
                let mut conn = pool.get_conn().await?;
                let values: Vec<mysql_async::Value> = params.iter().map(|p| p.into()).collect();
                conn.exec_drop(sql, values).await?;
                Ok(0)
            }
            DbEndpoint::Postgres(pool) => {
                let client = pool.get().await?;
                let pg_params = pg_params(params);
                let refs: Vec<&(dyn tokio_postgres::types::ToSql + Sync)> = pg_params
                    .iter()
                    .map(|p| p as &(dyn tokio_postgres::types::ToSql + Sync))
                    .collect();
                let rows = client.execute(sql, &refs).await?;
                Ok(rows)
            }
        }
    }

    /// Execute a statement that may return no rows without failing the
    /// task when it errors (used for best-effort DDL).
    pub async fn exec_best_effort(&self, sql: &str) -> anyhow::Result<()> {
        match self {
            DbEndpoint::MySql(pool) => {
                let mut conn = pool.get_conn().await?;
                conn.query_drop(sql).await?;
            }
            DbEndpoint::Postgres(pool) => {
                let client = pool.get().await?;
                client.batch_execute(sql).await?;
            }
        }
        Ok(())
    }

    /// Run a query and decode all rows.
    pub async fn query(&self, sql: &str, params: &[SqlValue]) -> anyhow::Result<QueryResult> {
        match self {
            DbEndpoint::MySql(pool) => {
                let mut conn = pool.get_conn().await?;
                let values: Vec<mysql_async::Value> = params.iter().map(|p| p.into()).collect();
                let result: Vec<mysql_async::Row> = conn.exec(sql, values).await?;
                let columns = result
                    .first()
                    .map(|r| {
                        r.columns_ref()
                            .iter()
                            .map(|c| c.name_str().to_string())
                            .collect()
                    })
                    .unwrap_or_default();
                let rows = result
                    .iter()
                    .map(|r| {
                        (0..r.len())
                            .map(|i| {
                                mysql_value_to_sql(
                                    &r.get::<mysql_async::Value, usize>(i)
                                        .unwrap_or(mysql_async::Value::NULL),
                                )
                            })
                            .collect()
                    })
                    .collect();
                Ok(QueryResult { columns, rows })
            }
            DbEndpoint::Postgres(pool) => {
                let client = pool.get().await?;
                let pg_params = pg_params(params);
                let refs: Vec<&(dyn tokio_postgres::types::ToSql + Sync)> = pg_params
                    .iter()
                    .map(|p| p as &(dyn tokio_postgres::types::ToSql + Sync))
                    .collect();
                let rows = client.query(sql, &refs).await?;
                let columns = rows
                    .first()
                    .map(|r| r.columns().iter().map(|c| c.name().to_string()).collect())
                    .unwrap_or_default();
                let mut out = Vec::with_capacity(rows.len());
                for row in &rows {
                    let mut vals = Vec::with_capacity(row.len());
                    for (i, col) in row.columns().iter().enumerate() {
                        vals.push(pg_cell_to_sql(row, i, col.type_()));
                    }
                    out.push(vals);
                }
                drop(client);
                Ok(QueryResult { columns, rows: out })
            }
        }
    }
}

/// Decode a Postgres cell into a driver-neutral value using the column's
/// OID type. Temporal / numeric / json / array types come back as text
/// (sources cast them to text in the SELECT when needed).
fn pg_cell_to_sql(
    row: &tokio_postgres::Row,
    idx: usize,
    ty: &tokio_postgres::types::Type,
) -> SqlValue {
    use tokio_postgres::types::Type;
    match *ty {
        Type::BOOL => row
            .try_get::<_, Option<bool>>(idx)
            .ok()
            .flatten()
            .map(SqlValue::Bool),
        Type::INT2 => row
            .try_get::<_, Option<i16>>(idx)
            .ok()
            .flatten()
            .map(|v| SqlValue::Int(v as i64)),
        Type::INT4 => row
            .try_get::<_, Option<i32>>(idx)
            .ok()
            .flatten()
            .map(|v| SqlValue::Int(v as i64)),
        Type::INT8 => row
            .try_get::<_, Option<i64>>(idx)
            .ok()
            .flatten()
            .map(SqlValue::Int),
        Type::FLOAT4 => row
            .try_get::<_, Option<f32>>(idx)
            .ok()
            .flatten()
            .map(|v| SqlValue::Float(v as f64)),
        Type::FLOAT8 => row
            .try_get::<_, Option<f64>>(idx)
            .ok()
            .flatten()
            .map(SqlValue::Float),
        Type::BYTEA => row
            .try_get::<_, Option<Vec<u8>>>(idx)
            .ok()
            .flatten()
            .map(SqlValue::Bytes),
        _ => None,
    }
    .unwrap_or(SqlValue::Null)
}
